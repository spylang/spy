"""
PROTOTYPE tests for the generation of the native stdlib manifest from the
redshifted modules. See spy.build.native_stdlib.
"""

import dataclasses

import py.path
import pytest

from spy.build.native_stdlib import (
    Manifest,
    NativeStdlib,
    get_native_stdlib,
)
from spy.fqn import FQN
from spy.vm.function import W_Func
from spy.vm.native import NativeRegistry, W_NativeCell, W_NativeFunc
from spy.vm.object import W_Object
from spy.vm.primitive import W_F32, W_F64, W_I32, W_U32
from spy.vm.vm import SPyVM

SRC = """
var counter = 10

def bump(n: i32) -> i32:
    global counter
    counter = counter + n
    return counter

def get_counter() -> i32:
    return counter

def reset() -> None:
    global counter
    counter = 0

def add_u32(a: u32, b: u32) -> u32:
    return a + b

def half(x: f64) -> f64:
    return x / 2.0

def twice(x: f32) -> f32:
    return x + x

def is_positive(x: i32) -> bool:
    return x > 0

def echo(s: str) -> str:
    return s

@struct
class P:
    x: i32

def get_x(p: P) -> i32:
    return p.x
"""


@pytest.fixture(scope="module")
def srcdir(tmp_path_factory) -> py.path.local:
    d = py.path.local(tmp_path_factory.mktemp("nmod"))
    d.join("nmod.spy").write(SRC)
    return d


@pytest.fixture(scope="module")
def nsl(srcdir) -> NativeStdlib:
    return get_native_stdlib(("nmod",), path=(str(srcdir),))


def make_vm(srcdir: py.path.local, nsl: NativeStdlib | None) -> SPyVM:
    vm = SPyVM(native_stdlib=nsl if nsl is not None else False)
    vm.path.append(str(srcdir))
    vm.import_("nmod")
    return vm


@pytest.fixture(scope="module")
def nvm(srcdir, nsl) -> SPyVM:
    return make_vm(srcdir, nsl)


def call(vm: SPyVM, name: str, *args: W_Object) -> W_Object:
    w_func = vm.lookup_global(FQN(name))
    assert isinstance(w_func, W_Func)
    return vm.fast_call(w_func, list(args))


class TestManifest:
    def test_random(self):
        m = get_native_stdlib().manifest
        assert [f.fqn for f in m.funcs] == [
            "random::seed",
            "random::random",
            "random::uniform",
        ]
        assert [(c.fqn, c.kind) for c in m.cells] == [
            ("_random::_ptr_global_random", "ptr")
        ]
        assert m.skipped == []
        seed = m.funcs[0]
        assert seed.params == ["builtins::u32"]
        assert seed.restype == "types::NoneType"
        assert seed.c_name == "spy_random$seed"
        assert seed.c_params == ["uint32_t"]
        assert seed.c_restype == "void"

    def test_shim_random(self):
        shim = get_native_stdlib().manifest.gen_shim()
        assert shim.splitlines() == [
            '#include "spy.h"',
            '#include "_random.h"',
            '#include "random.h"',
            "",
            "void WASM_EXPORT(native_spy_random__seed)(uint32_t a0) "
            "{ spy_random$seed(a0); }",
            "double WASM_EXPORT(native_spy_random__random)(void) "
            "{ return spy_random$random(); }",
            "double WASM_EXPORT(native_spy_random__uniform)(double a0, double a1) "
            "{ return spy_random$uniform(a0, a1); }",
            "void *WASM_EXPORT(native_spy__random___ptr_global_random)(void) "
            "{ return &spy__random$_ptr_global_random; }",
        ]

    def test_json_roundtrip(self, nsl, tmp_path):
        f = py.path.local(tmp_path).join("manifest.json")
        nsl.manifest.dump(f)
        assert Manifest.load(f) == nsl.manifest

    def test_custom_module(self, nsl):
        m = nsl.manifest
        assert {f.fqn: f.params for f in m.funcs} == {
            "nmod::bump": ["builtins::i32"],
            "nmod::get_counter": [],
            "nmod::reset": [],
            "nmod::add_u32": ["builtins::u32", "builtins::u32"],
            "nmod::half": ["builtins::f64"],
            "nmod::twice": ["builtins::f32"],
            "nmod::is_positive": ["builtins::i32"],
            "nmod::echo": ["builtins::str"],
        }
        assert [(c.fqn, c.kind) for c in m.cells] == [("nmod::counter", "i32")]

    def test_not_marshallable_stay_interpreted(self, nsl):
        skipped = {s.fqn: s.reason for s in nsl.manifest.skipped}
        assert skipped == {
            "nmod::get_x": "parameter of type nmod::P",
            # generated by @struct
            "nmod::P::__eq__": "parameter of type nmod::P",
            "nmod::P::__ne__": "parameter of type nmod::P",
        }


class TestCache:
    def test_key_follows_the_sources_not_the_path(self, nsl, tmp_path_factory):
        def new_dir(src: str) -> py.path.local:
            d = py.path.local(tmp_path_factory.mktemp("nmod"))
            d.join("nmod.spy").write(src)
            return d

        # same sources in another directory: same archive
        same = get_native_stdlib(("nmod",), path=(str(new_dir(SRC)),))
        assert same.archive == nsl.archive

        # changed sources: a different archive, with the new function
        changed = SRC + "\ndef extra(x: i32) -> i32:\n    return x\n"
        other = get_native_stdlib(("nmod",), path=(str(new_dir(changed)),))
        assert other.archive != nsl.archive
        assert "nmod::extra" in [f.fqn for f in other.manifest.funcs]
        assert "nmod::extra" not in [f.fqn for f in nsl.manifest.funcs]


class TestNativeCustomModule:
    def test_replaced_and_skipped(self, nvm):
        for name in ["bump", "get_counter", "add_u32", "half", "is_positive", "echo"]:
            assert isinstance(nvm.lookup_global(FQN(f"nmod::{name}")), W_NativeFunc)
        for name in ["get_x"]:
            w_func = nvm.lookup_global(FQN(f"nmod::{name}"))
            assert not isinstance(w_func, W_NativeFunc)

    def test_scalars(self, nvm):
        # u32 results and arguments above 2**31 survive the signed wasm i32
        w_res = call(nvm, "nmod::add_u32", W_U32(2**31), W_U32(2**31 - 1))
        assert nvm.unwrap(w_res) == 2**32 - 1
        assert nvm.unwrap(call(nvm, "nmod::half", W_F64(5.0))) == 2.5
        assert nvm.unwrap(call(nvm, "nmod::twice", W_F32(1.5))) == 3.0
        assert nvm.unwrap(call(nvm, "nmod::is_positive", W_I32(3))) is True
        assert nvm.unwrap(call(nvm, "nmod::is_positive", W_I32(-3))) is False

    def test_i32_cell_shared_state(self, nvm):
        w_cell = nvm.lookup_global(FQN("nmod::counter"))
        assert isinstance(w_cell, W_NativeCell)
        # the initial value is the one of the C global
        call(nvm, "nmod::reset")
        assert nvm.unwrap(w_cell.get()) == 0
        assert nvm.unwrap(call(nvm, "nmod::bump", W_I32(5))) == 5
        assert nvm.unwrap(w_cell.get()) == 5
        # written by the interpreter side, seen by the compiled code
        w_cell.set(W_I32(100))
        assert nvm.unwrap(call(nvm, "nmod::get_counter")) == 100

    def test_results_match_interpreter(self, srcdir, nvm):
        ivm = make_vm(srcdir, None)
        for vm in (nvm, ivm):
            call(vm, "nmod::reset")
        for n in [3, -1, 40]:
            w_native = call(nvm, "nmod::bump", W_I32(n))
            w_interp = call(ivm, "nmod::bump", W_I32(n))
            assert nvm.unwrap(w_native) == ivm.unwrap(w_interp)


class TestSignatureGuard:
    def test_out_of_sync_manifest_is_an_error(self, srcdir, nsl):
        ivm = make_vm(srcdir, None)
        w_bump = ivm.lookup_global(FQN("nmod::bump"))

        # same manifest, but pretend that `bump` takes an f64
        funcs = [
            dataclasses.replace(f, params=["builtins::f64"])
            if f.fqn == "nmod::bump"
            else f
            for f in nsl.manifest.funcs
        ]
        bad = dataclasses.replace(nsl.manifest, funcs=funcs)
        with pytest.raises(RuntimeError, match="native stdlib out of sync"):
            NativeRegistry(bad).maybe_replace_func(FQN("nmod::bump"), w_bump)

        # with the right manifest it is replaced
        w_new = NativeRegistry(nsl.manifest).maybe_replace_func(
            FQN("nmod::bump"), w_bump
        )
        assert isinstance(w_new, W_NativeFunc)
